type MessageKey = keyof typeof messages.en

const initialLocale = resolveInitialLocale()
const localeState = ref<Locale>(initialLocale)

export function useLocale() {
  const locale = computed(() => localeState.value)

  function setLocale(next: Locale) {
    localeState.value = next
    if (typeof window !== 'undefined') {
      window.localStorage.setItem(LOCALE_KEY, next)
    }
  }

  function toggleLocale() {
    setLocale(localeState.value === 'zh' ? 'en' : 'zh')
  }

  function t(key: MessageKey, vars?: Record<string, string | number>): string {
    const table = messages[localeState.value]
    let value: string = table[key] ?? messages.en[key] ?? key
    if (!vars) return value
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replace(new RegExp(`\\{${name}\\}`, 'g'), String(replacement))
    }
    return value
  }

  return {
    locale,
    setLocale,
    toggleLocale,
    t,
  }
}

function resolveInitialLocale(): Locale {
  if (typeof window === 'undefined') return 'zh'
  const saved = window.localStorage.getItem(LOCALE_KEY)
  if (saved === 'zh' || saved === 'en') return saved
  const language = window.navigator.language.toLowerCase()
  return language.startsWith('zh') ? 'zh' : 'en'
}
